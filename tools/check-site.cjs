const { chromium } = require('./browser/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1050}});
    const errors = [];
    page.on('pageerror', e=>errors.push(e.message));
    await page.goto('http://127.0.0.1:8000/');
    await page.getByRole('heading',{name:'한식, 이토록 다채롭다.'}).waitFor();
    await page.screenshot({path:'test-results/home-desktop.png',fullPage:true});
    await page.goto('http://127.0.0.1:8000/#/explore');
    await page.locator('#food-results .food-card').first().waitFor();
    assert.equal(await page.locator('#food-results .food-card').count(),16);
    await page.locator('[data-group="퓨전 한식"]').click();
    assert.equal(await page.locator('#food-results .food-card').count(),2);
    await page.locator('[data-group="전체"]').click();
    await page.locator('#food-search').fill('불고기');
    assert.equal(await page.locator('#food-results .food-card').count(),2);
    await page.locator('#food-search').fill('없는음식abc');
    await page.getByRole('heading',{name:'찾는 음식이 없어요.'}).waitFor();
    await page.getByRole('button',{name:'검색 초기화'}).click();
    assert.equal(await page.locator('#food-results .food-card').count(),16);
    const ids = await page.locator('#food-results .food-card').evaluateAll(links=>links.map(a=>a.getAttribute('href')));
    for(const hash of ids){
      await page.goto('http://127.0.0.1:8000/'+hash);
      await page.locator('.detail-copy h1').waitFor();
      await page.locator('#board-posts .empty').waitFor();
      const bg=await page.locator('.detail-photo').evaluate(el=>getComputedStyle(el).backgroundImage);
      assert.match(bg,/food-atlas.png/);
    }
    await page.goto('http://127.0.0.1:8000/#/food/bibimbap');
    await page.locator('[data-write]').first().click();
    await page.locator('[name="author"]').fill('맛탐험가');
    await page.locator('[name="title"]').fill('우리 집 비빔밥');
    await page.locator('[name="body"]').fill('참기름 한 방울과 봄나물!\n<script>window.hacked=true</script>');
    await page.locator('#post-form [type="submit"]').click();
    await page.locator('.post-row').waitFor();
    await page.reload();
    await page.locator('.post-row').click();
    await page.locator('#reader-content').getByRole('heading',{name:'우리 집 비빔밥'}).waitFor();
    assert.equal(await page.evaluate(()=>window.hacked),undefined);
    await page.locator('[data-edit]').click();
    await page.locator('[name="title"]').fill('수정한 비빔밥 이야기');
    await page.locator('#post-form [type="submit"]').click();
    await page.locator('.post-row').filter({hasText:'수정한 비빔밥 이야기'}).waitFor();
    await page.goto('http://127.0.0.1:8000/#/food/kimchi');
    await page.locator('#board-posts .empty').waitFor();
    await page.goto('http://127.0.0.1:8000/#/food/bibimbap');
    await page.locator('.post-row').click();
    page.once('dialog',dialog=>dialog.accept());
    await page.locator('[data-delete]').click();
    await page.locator('#board-posts .empty').waitFor();
    await page.setViewportSize({width:390,height:844});
    await page.goto('http://127.0.0.1:8000/');
    await page.screenshot({path:'test-results/home-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.goto('http://127.0.0.1:8000/#/explore');
    await page.locator('.food-grid .food-card').first().waitFor();
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    await page.goto('http://127.0.0.1:8000/#/food/tacos');
    await page.locator('.detail-copy h1').waitFor();
    await page.screenshot({path:'test-results/detail-mobile.png',fullPage:true});
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
    const response=await page.request.get('http://127.0.0.1:8000/assets/food-atlas.png');
    assert.equal(response.status(),200);
    assert.deepEqual(errors,[]);
    console.log('PASS: 16 detail pages, filters, search, create/reload/read/edit/delete, category isolation, escaped content, mobile layout, images, no JS errors.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
